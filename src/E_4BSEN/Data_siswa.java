    public void loadDataSiswa() {
        DefaultTableModel model = (DefaultTableModel) tbl_siswa.getModel();
        model.setRowCount(0);

        String sql = "SELECT s.nis, s.nama_siswa, s.jenis_kelamin, s.alamat, k.nama_kelas " +
                     "FROM siswa s JOIN kelas k ON s.id_kelas = k.id_kelas";

        Connection conn = koneksi.getKoneksi();
        if (conn == null) {
            JOptionPane.showMessageDialog(this, "Gagal terhubung ke database!", "Error Koneksi", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try (Statement st = conn.createStatement();
             ResultSet rs = st.executeQuery(sql)) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("nis"),
                    rs.getString("nama_siswa"),
                    rs.getString("jenis_kelamin"),
                    rs.getString("alamat"),
                    rs.getString("nama_kelas")
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal ambil data: " + e.getMessage());
        }
    }
    
