    private void btn_editActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editActionPerformed
        int row = tbl_siswa.getSelectedRow();
        if (row != -1) {
            // 1. Ambil semua data dari baris tabel
            String nis = tbl_siswa.getValueAt(row, 0).toString();
            String nama = tbl_siswa.getValueAt(row, 1).toString();
            String jk = tbl_siswa.getValueAt(row, 2).toString();
            String alamat = tbl_siswa.getValueAt(row, 3).toString();
            String kelas = tbl_siswa.getValueAt(row, 4).toString();

            // 2. Buka form tambah_siswa (tapi kirim datanya)
            tambah_siswa_baru formEdit = new tambah_siswa_baru();
            formEdit.siapkanEdit(nis, nama, jk, kelas, alamat); // Buat fungsi ini di form tambah_siswa
            formEdit.setVisible(true);
            this.dispose();
        }
    }//GEN-LAST:event_btn_editActionPerformed

    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed
        int row = tbl_siswa.getSelectedRow();
        if (row != -1) {
            String nis = tbl_siswa.getValueAt(row, 0).toString();
            int confirm = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus siswa dengan NIS: " + nis + "?", "Konfirmasi", JOptionPane.YES_NO_OPTION);

            if (confirm == JOptionPane.YES_OPTION) {
                try (Connection conn = koneksi.getKoneksi()) {
                    String sql = "DELETE FROM siswa WHERE nis = ?";
                    PreparedStatement ps = conn.prepareStatement(sql);
                    ps.setString(1, nis);

                    ps.executeUpdate();
                    JOptionPane.showMessageDialog(this, "Data Berhasil Dihapus!");

                    loadDataSiswa(); // Refresh tabel
                    btn_delete.setEnabled(false);
                    btn_edit.setEnabled(false);

                } catch (SQLException e) {
                    JOptionPane.showMessageDialog(this, "Gagal Hapus: " + e.getMessage());
                }
            }
        }
    }//GEN-LAST:event_btn_deleteActionPerformed

