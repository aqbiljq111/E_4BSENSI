    private void tf_simpandataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tf_simpandataActionPerformed

            DefaultTableModel model = (DefaultTableModel) table_absensi.getModel();
                if (model.getRowCount() == 0) {
                    JOptionPane.showMessageDialog(this, "Tabel kosong!");
                    return;
                }

                String tgl = tf_tanggal.getText();
                String pertemuan = tf_pertemuan.getText();
                String namaKelas = cb_kelas.getSelectedItem().toString();

                Connection conn = koneksi.getKoneksi();
                if (conn == null) {
                    JOptionPane.showMessageDialog(this, "Gagal terhubung ke database!", "Error Koneksi", JOptionPane.ERROR_MESSAGE);
                    return;
                }

                try {
                    conn.setAutoCommit(false); 

                    int idKelas = 0;
                    String sqlKelas = "SELECT id_kelas FROM kelas WHERE nama_kelas = ?";
                    PreparedStatement psKelas = conn.prepareStatement(sqlKelas);
                    psKelas.setString(1, namaKelas);
                    ResultSet rsK = psKelas.executeQuery();
                    if(rsK.next()) idKelas = rsK.getInt("id_kelas");

                    String sqlAbsen = "INSERT INTO absensi (id_jadwal, id_kelas, tanggal, pertemuan_ke) VALUES (1, ?, ?, ?)";
                    PreparedStatement psAbsen = conn.prepareStatement(sqlAbsen, Statement.RETURN_GENERATED_KEYS);
                    psAbsen.setInt(1, idKelas);
                    psAbsen.setString(2, tgl);
                    psAbsen.setString(3, pertemuan);
                    psAbsen.executeUpdate();
                    
                    ResultSet rsKey = psAbsen.getGeneratedKeys();
                    int idAbsenBaru = 0;
                    if (rsKey.next()) idAbsenBaru = rsKey.getInt(1);

                    String sqlDetail = "INSERT INTO detail_absensi (id_absensi, id_siswa, status) VALUES (?, (SELECT id_siswa FROM siswa WHERE nis = ?), ?)";
                    PreparedStatement psDetail = conn.prepareStatement(sqlDetail);

                    for (int i = 0; i < model.getRowCount(); i++) {
                        psDetail.setInt(1, idAbsenBaru);
                        psDetail.setString(2, model.getValueAt(i, 0).toString()); // NIS
                        psDetail.setString(3, model.getValueAt(i, 2).toString()); // Status (Hadir/Izin/dll)
                        psDetail.addBatch();
                    }
                    psDetail.executeBatch();
                    conn.commit();

                    JOptionPane.showMessageDialog(this, "Absensi berhasil disimpan!");
                } catch (SQLException e) {
                    JOptionPane.showMessageDialog(this, "Gagal simpan: " + e.getMessage());
            }
        
        
        if (tf_pertemuan.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pertemuan ke berapa?");
            tf_pertemuan.requestFocus();
            return;
        }
    }//GEN-LAST:event_tf_simpandataActionPerformed

