    private void btn_bukadaftarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_bukadaftarActionPerformed
        // 1. Ambil ID Kelas (Misal abang simpan ID-nya di ComboBox atau mapping)
        String namaKelas = cb_kelas.getSelectedItem().toString();

        String sql = "SELECT nis, nama_siswa FROM siswa " +
                     "JOIN kelas ON siswa.id_kelas = kelas.id_kelas " +
                     "WHERE kelas.nama_kelas = ?";

        DefaultTableModel model = (DefaultTableModel) table_absensi.getModel();
        model.setRowCount(0); // Reset tabel biar nggak numpuk

        Connection conn = koneksi.getKoneksi();
        if (conn == null) {
            JOptionPane.showMessageDialog(this, "Gagal terhubung ke database!", "Error Koneksi", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try (PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, namaKelas);
            ResultSet rs = ps.executeQuery();

            while (rs.next()) {
                // Masukkan NIS, Nama, dan default status (misal "Hadir")
                model.addRow(new Object[]{
                    rs.getString("nis"),
                    rs.getString("nama_siswa"),
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
        
        DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
        centerRenderer.setHorizontalAlignment(JLabel.CENTER);

        table_absensi.getColumnModel().getColumn(0).setCellRenderer(centerRenderer);
        table_absensi.getColumnModel().getColumn(2).setCellRenderer(centerRenderer);
        
        String[] status = {"Hadir", "Izin", "Sakit", "Alpa"};
        JComboBox comboBox = new JComboBox(status);

        // 2. Pasang ComboBox tersebut ke kolom index 2 (Status Kehadiran)
        table_absensi.getColumnModel().getColumn(2).setCellEditor(new DefaultCellEditor(comboBox));
    }//GEN-LAST:event_btn_bukadaftarActionPerformed

